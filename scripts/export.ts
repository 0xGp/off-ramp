// Regenerates exports/ from compiled artifacts and deployments/*.json.
// Run after `hardhat compile` or a deploy: `npm run export`.
import { readdir, readFile, writeFile } from "node:fs/promises";

const HEADER = "// Generated by scripts/export.ts. Do not edit by hand.\n";

const artifact = JSON.parse(
  await readFile("artifacts/contracts/MeloEscrow.sol/MeloEscrow.json", "utf8"),
) as { abi: unknown[] };

await writeFile(
  "exports/MeloEscrow.abi.ts",
  `${HEADER}export const meloEscrowAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);

type Deployment = { chainId: number; escrow: string; usdc: string; deployBlock: string };

const files = (await readdir("deployments").catch(() => [] as string[])).filter((f) => f.endsWith(".json"));
const entries: string[] = [];
for (const file of files.sort()) {
  const d = JSON.parse(await readFile(`deployments/${file}`, "utf8")) as Deployment;
  entries.push(
    `  ${d.chainId}: { escrow: "${d.escrow}", usdc: "${d.usdc}", deployBlock: ${d.deployBlock}n },`,
  );
}

await writeFile(
  "exports/addresses.ts",
  `${HEADER}import type { Address } from "viem";

export type EscrowDeployment = { escrow: Address; usdc: Address; deployBlock: bigint };

export const escrowDeployments: Record<number, EscrowDeployment> = {
${entries.join("\n")}
};
`,
);

console.log(`exports/ updated (${entries.length} deployment${entries.length === 1 ? "" : "s"})`);
